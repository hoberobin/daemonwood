import { readFile, writeFile, access } from "node:fs/promises";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";
import { decodePNG, encodePNG, bounds, blit } from "./lib/png.mjs";
import { cuts } from "./lib/sheet.mjs";

/* Station-work sheets are optional, one familiar at a time. A familiar with
   art/source/familiars/<id>-stations.png gets an exported 4x2 sheet and a line
   in src/station-sheets.js; one without keeps drawing exactly as it does today.

   Each sheet is exported at its familiar's BASE sheet scale, read from the base
   atlas, so the body in a station frame is the same size as in every other
   frame. A station figure too big for its cell at that scale fails loudly here
   rather than drawing a familiar that grows when it picks up a hammer. */
const root = fileURLToPath(new URL("../", import.meta.url));
const contract = JSON.parse(await readFile(resolve(root, "art/source/station-contract.json")));
const base = JSON.parse(await readFile(resolve(root, "assets/sprites/familiar-atlas-v1.json")));
const { frameSize, columns, rows, baseline } = contract;
const hash = (buffer) => createHash("sha256").update(buffer).digest("hex");
const exists = (path) => access(path).then(() => true, () => false);
const atlas = { ...contract, familiars: {} };

for (const [id, entry] of Object.entries(base.familiars)) {
  const source = `art/source/familiars/${id}${contract.sourceSuffix}.png`;
  if (!await exists(resolve(root, source))) continue;
  const raw = await readFile(resolve(root, source));
  const image = decodePNG(raw);
  const xs = cuts(image, columns, false), ys = cuts(image, rows, true);
  const boxes = [];
  for (let row = 0; row < rows; row++) for (let col = 0; col < columns; col++) {
    const box = bounds(image, [xs[col], ys[row], xs[col + 1] - xs[col], ys[row + 1] - ys[row]]);
    if (!box) throw new Error(`${id}: empty station frame ${boxes.length}`);
    boxes.push(box);
  }
  const scale = Math.min(1, base.maxSilhouette / Math.max(...entry.sourceBounds.flatMap((box) => box.slice(2))));
  const out = { width: columns * frameSize, height: rows * frameSize, data: Buffer.alloc(columns * rows * frameSize ** 2 * 4) };
  boxes.forEach((box, i) => {
    const width = Math.max(1, Math.round(box[2] * scale)), height = Math.max(1, Math.round(box[3] * scale));
    if (width > frameSize - 8 || height > baseline - 3) {
      throw new Error(`${id}: station frame ${i} is ${width}x${height} at the base scale and will not fit its cell. Draw the figure and its prop smaller.`);
    }
    blit(image, box, out, i % columns * frameSize + Math.floor((frameSize - width) / 2),
      Math.floor(i / columns) * frameSize + baseline + 1 - height, width, height);
  });
  const exported = `assets/sprites/${id}-stations-v1.png`;
  const bytes = encodePNG(out);
  await writeFile(resolve(root, exported), bytes);
  atlas.familiars[id] = { image: `./${exported}`, source, sourceHash: hash(raw), exportHash: hash(bytes), sourceBounds: boxes };
  console.log(`${id}: ${boxes.length} station frames → ${exported}`);
}

await writeFile(resolve(root, "assets/sprites/familiar-stations-v1.json"), JSON.stringify(atlas, null, 2) + "\n");
await writeFile(resolve(root, "src/station-sheets.js"), stationModule(atlas));
console.log(`Station sheets: ${Object.keys(atlas.familiars).length} of ${Object.keys(base.familiars).length} familiars have station art.`);

export function stationModule({ familiars }) {
  const lines = Object.entries(familiars).map(([id, { image }]) => `  ${JSON.stringify(id)}: ${JSON.stringify(image)}`);
  return `/* Generated by scripts/export-station-art.mjs — do not edit by hand.
   Which familiars have a station-work sheet (art/source/station-contract.json).
   A familiar missing here draws its ordinary frames at every station. */
export const STATION_SHEETS = Object.freeze({${lines.length ? `\n${lines.join(",\n")}\n` : ""}});
`;
}
